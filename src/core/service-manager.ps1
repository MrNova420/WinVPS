# ============================================================

function Test-ServiceHealth {
    param([string]$Name)

    $svc = Get-ServiceDefinition $Name
    if (-not $svc -or -not $svc.HealthCheck) { return @{ Status = 'unknown'; Message = 'No health check configured' } }

    $hc = $svc.HealthCheck
    $retries = 3
    $timeout = 5

    # TCP port check
    if ($hc -match '^\d+$') {
        $port = [int]$hc
        for ($i = 0; $i -lt $retries; $i++) {
            $conn = Get-NetTCPConnection -LocalPort $port -State Listen -ErrorAction SilentlyContinue
            if ($conn) {
                return @{ Status = 'healthy'; Message = "TCP port $port is listening"; Latency = 0 }
            }
            Start-Sleep -Seconds 1
        }
        return @{ Status = 'unhealthy'; Message = "TCP port $port not listening"; Latency = -1 }
    }

    # HTTP health check
    if ($hc -match '^https?://') {
        for ($i = 0; $i -lt $retries; $i++) {
            try {
                $sw = [System.Diagnostics.Stopwatch]::StartNew()
                $response = Invoke-WebRequest -Uri $hc -TimeoutSec $timeout -UseBasicParsing -ErrorAction Stop
                $sw.Stop()
                if ($response.StatusCode -eq 200) {
                    return @{ Status = 'healthy'; Message = "HTTP 200 OK"; Latency = $sw.ElapsedMilliseconds }
                }
            } catch {
                if ($i -eq $retries - 1) {
                    return @{ Status = 'unhealthy'; Message = "HTTP check failed: $($_.Exception.Message)"; Latency = -1 }
                }
                Start-Sleep -Seconds 1
            }
        }
    }

    # Process check (fallback)
    if (Test-ServiceRunning $Name) {
        return @{ Status = 'healthy'; Message = 'Process is running'; Latency = 0 }
    }
    return @{ Status = 'unhealthy'; Message = 'Process not running'; Latency = -1 }
}

function Get-HealthHistory {
    param([string]$Name, [int]$MaxEntries = 50)

    $historyFile = Join-Path (Get-ServiceDir $Name) 'health_history.json'
    if (-not (Test-Path $historyFile)) { return @() }

    $history = Get-Content $historyFile -Raw | ConvertFrom-Json
    return $history | Select-Object -Last $MaxEntries
}

function Add-HealthHistoryEntry {
    param([string]$Name, [string]$Status, [string]$Message, [int]$Latency = 0)

    $historyFile = Join-Path (Get-ServiceDir $Name) 'health_history.json'
    $history = @()

    if (Test-Path $historyFile) {
        $history = @(Get-Content $historyFile -Raw | ConvertFrom-Json)
    }

    $entry = [PSCustomObject]@{
        Timestamp = (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
        Status    = $Status
        Message   = $Message
        Latency   = $Latency
    }

    $history = @($history) + @($entry)
    if ($history.Count -gt 200) { $history = $history[-200..-1] }
    $history | ConvertTo-Json -Depth 5 | Out-File -FilePath $historyFile -Encoding ascii -Force
}

