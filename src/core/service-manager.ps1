    'backup'        { Backup-Service -Name $ServiceName }
    'restore'       { Restore-Service -Name $ServiceName }
    'exec'          { Invoke-ServiceExec -Name $ServiceName -Command $ExecCommand }
    'install-deps'  { Install-ServiceDependencies -Name $ServiceName }
    default         { Write-Host "  Usage: service-manager.ps1 {list|add|remove|start|stop|restart|status|detail|health|metrics|deps|graph|logs|env|backup|restore|exec|install-deps}" }
}
