# --- PID / RUNNING STATE ---
# ============================================================

function Test-ServiceRunning($name) {
    $pf = Get-ServicePidFile $name
    if (-not (Test-Path $pf)) { return $false }
    $pid = [int](Get-Content $pf -ErrorAction SilentlyContinue)
    if ($pid -le 0) { return $false }
    $proc = Get-Process -Id $pid -ErrorAction SilentlyContinue
    return ($null -ne $proc)
}

function Get-ServicePid($name) {
    $pf = Get-ServicePidFile $name
    if (-not (Test-Path $pf)) { return 0 }
    return [int](Get-Content $pf -ErrorAction SilentlyContinue)
}

function Get-ServiceProcess($name) {
    $pid = Get-ServicePid $name
    if ($pid -gt 0) { return (Get-Process -Id $pid -ErrorAction SilentlyContinue) }
    return $null
}

function Get-ServiceStatus($name) {
    if (-not (Test-ServiceRegistered $name)) { return 'unknown' }
    if (Test-ServiceRunning $name) { return 'running' }
    return 'stopped'
}

function Get-ServiceMemoryMB($name) {
    $proc = Get-ServiceProcess $name
    if ($proc) { return [math]::Round($proc.WorkingSet64 / 1MB, 1) }
    return 0
}

function Get-ServiceCpuPercent($name) {
    $proc = Get-ServiceProcess $name
    if ($proc) {
        try { return [math]::Round($proc.CPU, 1) } catch { return 0 }
    }
    return 0
}

function Get-ServiceUptime($name) {
    $proc = Get-ServiceProcess $name
    if ($proc) {
        $uptime = (Get-Date) - $proc.StartTime
        return "{0}h {1}m {2}s" -f [math]::Floor($uptime.TotalHours), $uptime.Minutes, $uptime.Seconds
    }
    return ''
}

