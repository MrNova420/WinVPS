# ============================================================

function Get-DependencyGraph {
    $services = Read-ServicesConf
    $graph = @{}

    foreach ($svc in $services) {
        $graph[$svc.Name] = @{
            Service = $svc
            DependsOn = if ($svc.DependsOn) {
                ($svc.DependsOn -split ',' | ForEach-Object { $_.Trim() }) | Where-Object { $_ }
            } else { @() }
            Dependents = @()
        }
    }

    # Build reverse dependencies
    foreach ($name in $graph.Keys) {
        foreach ($dep in $graph[$name].DependsOn) {
            if ($graph.ContainsKey($dep)) {
                $graph[$dep].Dependents = @($graph[$dep].Dependents) + @($name)
            }
        }
    }

    return $graph
}

function Get-StartOrder {
    param([string[]]$ServiceNames)

    $graph = Get-DependencyGraph
    $resolved = [System.Collections.ArrayList]::new()
    $visited = @{}

    function Visit($name) {
        if ($visited[$name]) { return }
        $visited[$name] = $true
        if ($graph.ContainsKey($name)) {
            foreach ($dep in $graph[$name].DependsOn) {
                if ($graph.ContainsKey($dep)) { Visit $dep }
            }
        }
        [void]$resolved.Add($name)
    }

    foreach ($n in $ServiceNames) { Visit $n }
    return $resolved
}

function Show-DependencyGraph {
    $graph = Get-DependencyGraph
    Write-Host ''
    Write-Host "  ${Bold}Service Dependency Graph${NC}"
    Write-Host "  ${Dim}------------------------------------------${NC}"
    Write-Host ''

    foreach ($name in ($graph.Keys | Sort-Object)) {
        $node = $graph[$name]
        $status = Get-ServiceStatus $name
        $icon = switch ($status) { 'running' { "${Green}*${NC}" } 'stopped' { "${Red}o${NC}" } default { "${Dim}?${NC}" } }

        $deps = if ($node.DependsOn.Count -gt 0) { " ${Dim}<-- $($node.DependsOn -join ', ')${NC}" } else { '' }
        $dependents = if ($node.Dependents.Count -gt 0) { " ${Dim}--> $($node.Dependents -join ', ')${NC}" } else { '' }

        Write-Host "  $icon ${Bold}$name${NC}$deps$dependents"
    }
    Write-Host ''
}

