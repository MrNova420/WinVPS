function Get-ServiceMetrics {
    param([string]$Name)

    $metrics = @{
        Name       = $Name
        Status     = Get-ServiceStatus $Name
        MemoryMB   = Get-ServiceMemoryMB $Name
        CpuPercent = Get-ServiceCpuPercent $Name
        Uptime     = Get-ServiceUptime $Name
        Pid        = Get-ServicePid $Name
        Health     = Test-ServiceHealth $Name
        Timestamp  = (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
    }

    # Disk usage
    $dataDir = Get-ServiceDataDir $Name
    if (Test-Path $dataDir) {
        try {
            $size = (Get-ChildItem -Path $dataDir -Recurse -File -ErrorAction SilentlyContinue | Measure-Object -Property Length -Sum).Sum
            $metrics.DiskMB = [math]::Round($size / 1MB, 1)
        } catch {
            $metrics.DiskMB = 0
        }
    } else {
        $metrics.DiskMB = 0
    }

    # Log size
    $logDir = Join-Path (Get-ServiceDir $Name) 'logs'
    if (Test-Path $logDir) {
        try {
            $logSize = (Get-ChildItem -Path $logDir -File -ErrorAction SilentlyContinue | Measure-Object -Property Length -Sum).Sum
            $metrics.LogMB = [math]::Round($logSize / 1MB, 1)
        } catch {
            $metrics.LogMB = 0
        }
    } else {
        $metrics.LogMB = 0
    }

    return $metrics
}

function Save-ServiceMetrics {
    param([string]$Name, [hashtable]$Metrics)

    $metricsFile = Join-Path (Get-ServiceDir $Name) 'metrics_history.json'
    $history = @()

    if (Test-Path $metricsFile) {
        try { $history = @(Get-Content $metricsFile -Raw | ConvertFrom-Json) } catch { $history = @() }
    }

    $entry = [PSCustomObject]$Metrics
    $history = @($history) + @($entry)
    if ($history.Count -gt 500) { $history = $history[-500..-1] }
    $history | ConvertTo-Json -Depth 5 | Out-File -FilePath $metricsFile -Encoding ascii -Force
}

function Get-MetricsHistory {
    param([string]$Name, [int]$MaxEntries = 100)

    $metricsFile = Join-Path (Get-ServiceDir $Name) 'metrics_history.json'
    if (-not (Test-Path $metricsFile)) { return @() }
    try {
        $history = @(Get-Content $metricsFile -Raw | ConvertFrom-Json)
        return $history | Select-Object -Last $MaxEntries
    } catch { return @() }
}

