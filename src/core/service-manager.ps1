function Resolve-ServiceType {
    param([string]$ScriptPath, [string]$Type = 'auto')

    if ($Type -ne 'auto') { return $Type }

    $ext = [System.IO.Path]::GetExtension($ScriptPath).ToLower()
    $baseName = [System.IO.Path]::GetFileName($ScriptPath).ToLower()

    if ($baseName -eq 'dockerfile' -or $baseName -eq 'docker-compose.yml' -or $baseName -eq 'docker-compose.yaml' -or $baseName -eq 'compose.yml' -or $baseName -eq 'compose.yaml') { return 'docker' }
    if ($baseName -eq 'deno.json' -or $baseName -eq 'deno.jsonc') { return 'deno' }
    if ($baseName -eq 'bun.lockb' -or $baseName -eq 'bunfig.toml') { return 'bun' }
    if ($ext -eq '.exe') { return 'exec' }
    if ($ext -eq '.jar') { return 'java' }

    switch ($ext) {
        '.js'  { 'node' }
        '.mjs' { 'node' }
        '.cjs' { 'node' }
        '.ts'  { 'node' }
        '.mts' { 'node' }
        '.cts' { 'node' }
        '.tsx' { 'node' }
        '.jsx' { 'node' }
        '.py'  { 'python' }
        '.pyw' { 'python' }
        '.ps1' { 'ps' }
        '.cmd' { 'cmd' }
        '.bat' { 'cmd' }
        '.go'  { 'go' }
        '.rb'  { 'ruby' }
        '.rs'  { 'rust' }
        '.java' { 'java' }
        '.php'  { 'php' }
        '.lua'  { 'lua' }
        '.sh'  { 'sh' }
        '.bash' { 'sh' }
        '.csproj' { 'dotnet' }
        '.sln'    { 'dotnet' }
        default   { 'ps' }
    }
}

