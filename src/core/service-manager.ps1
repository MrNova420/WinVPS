function Get-LaunchCommand {
    param([string]$Script, [string]$Type, [string]$WorkingDir = '')

    $wd = if ($WorkingDir) { $WorkingDir } elseif ($Script) { Split-Path $Script -Parent } else { '' }

    switch ($Type) {
        'ps' {
            return @{ File = 'powershell.exe'; Args = "-NoProfile -NonInteractive -ExecutionPolicy Bypass -File `"$Script`" start" }
        }
        'cmd' {
            return @{ File = 'cmd.exe'; Args = "/c `"$Script`"" }
        }
        'node' {
            $node = Get-Command node -ErrorAction SilentlyContinue
            if (-not $node) { return $null }
            $ext = [System.IO.Path]::GetExtension($Script).ToLower()
            if ($ext -in '.ts', '.mts', '.cts', '.tsx') {
                $bun = Get-Command bun -ErrorAction SilentlyContinue
                if ($bun) {
                    return @{ File = $bun.Source; Args = "`"$Script`"" }
                }
                $tsx = Get-Command tsx -ErrorAction SilentlyContinue
                if ($tsx) {
                    return @{ File = $node.Source; Args = "--import tsx `"$Script`"" }
                }
                $tsNode = Get-Command ts-node -ErrorAction SilentlyContinue
                if ($tsNode) {
                    return @{ File = $node.Source; Args = "--loader ts-node/esm `"$Script`"" }
                }
                return @{ File = $node.Source; Args = "`"$Script`"" }
            }
            return @{ File = $node.Source; Args = "`"$Script`"" }
        }
        'python' {
            $python = Get-Command python3 -ErrorAction SilentlyContinue
            if (-not $python) { $python = Get-Command python -ErrorAction SilentlyContinue }
            if (-not $python) { return $null }
            return @{ File = $python.Source; Args = "`"$Script`"" }
        }
        'go' {
            $go = Get-Command go -ErrorAction SilentlyContinue
            if (-not $go) { return $null }
            return @{ File = $go.Source; Args = "run `"$Script`"" }
        }
        'dotnet' {
            $dotnet = Get-Command dotnet -ErrorAction SilentlyContinue
            if (-not $dotnet) { return $null }
            return @{ File = $dotnet.Source; Args = "run --project `"$Script`"" }
        }
        'docker' {
            $docker = Get-Command docker -ErrorAction SilentlyContinue
            if (-not $docker) { return $null }
            return @{ File = $docker.Source; Args = "compose -f `"$Script`" up -d" }
        }
        'deno' {
            $deno = Get-Command deno -ErrorAction SilentlyContinue
            if (-not $deno) { return $null }
            return @{ File = $deno.Source; Args = "run --allow-all `"$Script`"" }
        }
        'bun' {
            $bun = Get-Command bun -ErrorAction SilentlyContinue
            if (-not $bun) { return $null }
            return @{ File = $bun.Source; Args = "`"$Script`"" }
        }
        'ruby' {
            $ruby = Get-Command ruby -ErrorAction SilentlyContinue
            if (-not $ruby) { return $null }
            return @{ File = $ruby.Source; Args = "`"$Script`"" }
        }
        'rust' {
            $cargo = Get-Command cargo -ErrorAction SilentlyContinue
            if (-not $cargo) { return $null }
            return @{ File = $cargo.Source; Args = "run --release" }
        }
        'java' {
            $java = Get-Command java -ErrorAction SilentlyContinue
            if (-not $java) { return $null }
            if ($Script -match '\.jar$') {
                return @{ File = $java.Source; Args = "-jar `"$Script`"" }
            }
            return @{ File = $java.Source; Args = "`"$Script`"" }
        }
        'php' {
            $php = Get-Command php -ErrorAction SilentlyContinue
            if (-not $php) { return $null }
            return @{ File = $php.Source; Args = "`"$Script`"" }
        }
        'lua' {
            $lua = Get-Command lua -ErrorAction SilentlyContinue
            if (-not $lua) { $lua = Get-Command lua54 -ErrorAction SilentlyContinue }
            if (-not $lua) { return $null }
            return @{ File = $lua.Source; Args = "`"$Script`"" }
        }
        'sh' {
            return @{ File = 'bash.exe'; Args = "`"$Script`"" }
        }
        'exec' {
            return @{ File = $Script; Args = '' }
        }
        default {
            return @{ File = $Script; Args = '' }
        }
    }
}

