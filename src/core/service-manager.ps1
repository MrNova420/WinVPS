function Start-ManagedService {
    param([string]$Name, [switch]$Force)

    $svc = Get-ServiceDefinition $Name
    if (-not $svc) { Err "Service '$Name' not found"; return $false }

    $dir = Get-ServiceDir $Name
    $pidFile = Get-ServicePidFile $Name
    $stdoutLog = Get-ServiceLogFile $Name 'stdout'
    $stderrLog = Get-ServiceLogFile $Name 'stderr'

    # Ensure directory structure
    Ensure-ServiceDir $Name

    # Check if already running
    if ((Test-ServiceRunning $Name) -and -not $Force) {
        $pid = Get-ServicePid $Name
        Log "$Name already running (PID $pid)"
        return $true
    }

    # Stop existing if force
    if ($Force -and (Test-Path $pidFile)) {
        Stop-ManagedService -Name $Name -Graceful
    }

    # Clean up stale PID
    if (Test-Path $pidFile) { Remove-Item $pidFile -Force -ErrorAction SilentlyContinue }

    # Resolve dependencies
    if ($svc.DependsOn) {
        foreach ($dep in ($svc.DependsOn -split ',')) {
            $dep = $dep.Trim()
            if ($dep -and -not (Test-ServiceRunning $dep)) {
                Log "Starting dependency: $dep"
                Start-ManagedService -Name $dep | Out-Null
            }
        }
    }

    # Resolve type
    $type = Resolve-ServiceType -ScriptPath $svc.Script -Type $svc.Type
    $workingDir = if ($svc.Script) { Split-Path $svc.Script -Parent } else { '' }

    # Build launch command
    $launch = Get-LaunchCommand -Script $svc.Script -Type $type -WorkingDir $workingDir
    if (-not $launch) {
        Err "Cannot launch '$Name' - required runtime not found"
        return $false
    }

    # Set environment
    $envVars = Get-ServiceEnv $Name
    foreach ($k in $envVars.Keys) {
        [Environment]::SetEnvironmentVariable($k, $envVars[$k], 'Process')
    }

    # Start process
    try {
        $pinfo = New-Object System.Diagnostics.ProcessStartInfo
        $pinfo.FileName = $launch.File
        $pinfo.Arguments = $launch.Args
        $pinfo.UseShellExecute = $false
        $pinfo.CreateNoWindow = $true
        $pinfo.RedirectStandardOutput = $true
        $pinfo.RedirectStandardError = $true
        if ($workingDir -and (Test-Path $workingDir)) {
            $pinfo.WorkingDirectory = $workingDir
        }
        $proc = [System.Diagnostics.Process]::Start($pinfo)
        $proc.Id | Out-File -FilePath $pidFile -Encoding ascii -Force

        # Write service config
        $confFile = Get-ServiceConfigFile $Name
        @"
# Service: $Name
WINVPS_SVC_NAME=$Name
WINVPS_SVC_TYPE=$type
WINVPS_SVC_PORT=$($svc.Port)
WINVPS_SVC_PID=$($proc.Id)
WINVPS_SVC_STARTED=$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
"@ | Out-File -FilePath $confFile -Encoding ascii -Force

        Start-Sleep -Seconds 2
        if (-not $proc.HasExited) {
            Log "$Name started (PID $($proc.Id), type=$type)"
            return $true
        } else {
            Warn "$Name exited immediately (code $($proc.ExitCode))"
            Remove-Item $pidFile -Force -ErrorAction SilentlyContinue
            return $false
        }
    } catch {
        Warn "$Name failed to start: $_"
        return $false
    }
}

function Stop-ManagedService {
    param([string]$Name, [switch]$Graceful, [int]$Timeout = 10)

    $pidFile = Get-ServicePidFile $Name
    if (-not (Test-Path $pidFile)) {
        Warn "$Name not running"
        return
    }

    $pid = [int](Get-Content $pidFile -ErrorAction SilentlyContinue)
    if ($pid -gt 0) {
        $proc = Get-Process -Id $pid -ErrorAction SilentlyContinue
        if ($proc) {
            try {
                if ($Graceful) {
                    # Try to close window gracefully
                    $proc.CloseMainWindow() | Out-Null
                    $waited = 0
                    while (-not $proc.HasExited -and $waited -lt $Timeout) {
                        Start-Sleep -Seconds 1
                        $waited++
                    }
                }
                if (-not $proc.HasExited) {
                    $proc.Kill()
                }
                Start-Sleep -Milliseconds 500
                Log "$Name stopped (PID $pid)"
            } catch {
                Warn "Could not stop $Name : $_"
            }
        }
    }
    Remove-Item $pidFile -Force -ErrorAction SilentlyContinue

    # Clean config
    $confFile = Get-ServiceConfigFile $Name
    if (Test-Path $confFile) { Remove-Item $confFile -Force -ErrorAction SilentlyContinue }
}

# ============================================================
# --- SERVICE ADD/REMOVE ---
# ============================================================

function Add-ManagedService {
    param(
        [string]$Name, [string]$Script, [string]$Type = 'auto', [int]$Port = 0,
        [bool]$AutoStart = $false, [string]$HealthCheck = '', [string]$DependsOn = '',
        [string]$Description = '', [string]$WorkingDir = '', [string]$User = '',
        [int]$MaxRestarts = 5, [int]$RestartBackoff = 10, [int]$LogRetentionDays = 30
    )

    if (-not $Name -or -not $Script) { Err "Name and Script required"; return }
    if (Test-ServiceRegistered $Name) { Err "Service '$Name' already exists"; return }

    $type = Resolve-ServiceType -ScriptPath $Script -Type $Type

    $entry = [PSCustomObject]@{
        Name = $Name; Script = $Script; Type = $type; Port = $Port
        AutoStart = $AutoStart; HealthCheck = $HealthCheck; DependsOn = $DependsOn; Description = $Description
    }

    # Ensure services.conf exists
    if (-not (Test-Path $ServicesConf)) {
        "# WinVPS Service Definitions`n" | Out-File -FilePath $ServicesConf -Encoding ascii
    }

    Write-ServicesConfEntry -Entry $entry
    Ensure-ServiceDir $Name
    Log "Added service: $Name (type=$type, port=$Port)"
}

function Remove-ManagedService {
    param([string]$Name, [switch]$KeepData)

    if (-not $Name) { Err "Service name required"; return }
    if (-not (Test-ServiceRegistered $Name)) { Err "Service '$Name' not found"; return }

    # Stop if running
    if (Test-ServiceRunning $Name) { Stop-ManagedService -Name $Name }

    # Remove from services.conf
    Remove-ServicesConfEntry -Name $Name

    # Clean up directory
    if (-not $KeepData) {
        $dir = Get-ServiceDir $Name
        if (Test-Path $dir) { Remove-Item $dir -Recurse -Force -ErrorAction SilentlyContinue }
    }

    Log "Service '$Name' removed"
}

