function Get-ServicesConfPath { return $ServicesConf }

function Read-ServicesConf {
    $services = [System.Collections.ArrayList]::new()
    if (-not (Test-Path $ServicesConf)) { return $services }

    Get-Content $ServicesConf -Encoding ascii -ErrorAction SilentlyContinue | ForEach-Object {
        $line = $_.Trim()
        if ($line -eq '' -or $line.StartsWith('#')) { return }
        $parts = $line -split '\|', -1
        if ($parts.Count -ge 2) {
            [void]$services.Add([PSCustomObject]@{
                Name        = $parts[0].Trim()
                Script      = $parts[1].Trim()
                Type        = if ($parts.Count -ge 3 -and $parts[2].Trim()) { $parts[2].Trim() } else { 'auto' }
                Port        = if ($parts.Count -ge 4 -and $parts[3].Trim()) { [int]$parts[3].Trim() } else { 0 }
                AutoStart   = if ($parts.Count -ge 5 -and $parts[4].Trim()) { $parts[4].Trim() -eq 'true' } else { $false }
                HealthCheck = if ($parts.Count -ge 6) { $parts[5].Trim() } else { '' }
                DependsOn   = if ($parts.Count -ge 7) { $parts[6].Trim() } else { '' }
                Description = if ($parts.Count -ge 8) { $parts[7].Trim() } else { '' }
            })
        }
    }
    return $services
}

function Write-ServicesConf {
    param([array]$Services)

    $lines = @(
        "# WinVPS Service Definitions - v2.0"
        "# Format: name|script|type|port|auto_start|health_check|depends_on|description"
        "# Type: ps|cmd|node|deno|bun|python|go|rust|ruby|java|php|lua|sh|dotnet|docker|exec"
        "# Auto-generated by WinVPS Service Manager"
        ""
    )

    foreach ($svc in $Services) {
        $lines += "$($svc.Name)|$($svc.Script)|$($svc.Type)|$($svc.Port)|$($svc.AutoStart.ToString().ToLower())|$($svc.HealthCheck)|$($svc.DependsOn)|$($svc.Description)"
    }

    $lines | Out-File -FilePath $ServicesConf -Encoding ascii -Force
}

function Write-ServicesConfEntry {
    param([PSCustomObject]$Entry)
    $line = "$($Entry.Name)|$($Entry.Script)|$($Entry.Type)|$($Entry.Port)|$($Entry.AutoStart.ToString().ToLower())|$($Entry.HealthCheck)|$($Entry.DependsOn)|$($Entry.Description)"
    Add-Content -Path $ServicesConf -Value $line -Encoding ascii
}

function Remove-ServicesConfEntry {
    param([string]$Name)
    $lines = Get-Content $ServicesConf -Encoding ascii
    $filtered = $lines | Where-Object {
        $_ -notmatch "^\s*\Q$Name\E\s*\|"
    }
    $filtered | Out-File -FilePath $ServicesConf -Encoding ascii -Force
}

