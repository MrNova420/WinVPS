switch ($Action) {
    'list'          { Show-ServiceList }
    'add'           { Add-ManagedService -Name $ServiceName -Script $ScriptPath -Type $Type -Port $Port -AutoStart $AutoStart -HealthCheck $HealthCheck -DependsOn $DependsOn -Description $Description -WorkingDir $WorkingDir -User $User -MaxRestarts $MaxRestarts -RestartBackoff $RestartBackoff -LogRetentionDays $LogRetentionDays }
    'remove'        { Remove-ManagedService -Name $ServiceName }
    'start'         { Start-ManagedService -Name $ServiceName }
    'stop'          { Stop-ManagedService -Name $ServiceName -Graceful }
    'restart'       { Stop-ManagedService -Name $ServiceName; Start-Sleep -Seconds 2; Start-ManagedService -Name $ServiceName }
    'status'        { Show-ServiceList }
    'detail'        { Show-ServiceDetail -Name $ServiceName }
    'health'        { $h = Test-ServiceHealth -Name $ServiceName; Write-Host "$($h.Status): $($h.Message)" }
    'metrics'       { $m = Get-ServiceMetrics -Name $ServiceName; $m | ConvertTo-Json -Depth 3 }
    'deps'          { Show-DependencyGraph }
    'graph'         { Show-DependencyGraph }
    'logs'          { Show-ServiceLogs -Name $ServiceName -Lines $LogLines }
