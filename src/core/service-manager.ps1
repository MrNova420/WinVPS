function Get-ServiceDir($name) { Join-Path $ServicesDir $name }

function Ensure-ServiceDir {
    param([string]$Name)
    $dir = Get-ServiceDir $Name
    $subdirs = @($dir, (Join-Path $dir 'data'), (Join-Path $dir 'logs'), (Join-Path $dir 'secrets'))
    foreach ($d in $subdirs) {
        if (-not (Test-Path $d)) { New-Item -ItemType Directory -Path $d -Force | Out-Null }
    }
}

function Get-ServicePidFile($name) { Join-Path (Get-ServiceDir $name) 'pid' }
function Get-ServiceLogFile($name, $type = 'stdout') { Join-Path (Get-ServiceDir $name) "logs/$type.log" }
function Get-ServiceEnvFile($name) { Join-Path (Get-ServiceDir $name) '.env' }
function Get-ServiceConfigFile($name) { Join-Path (Get-ServiceDir $name) 'service.conf' }
function Get-ServiceDataDir($name) { Join-Path (Get-ServiceDir $name) 'data' }
function Get-ServiceSecretsDir($name) { Join-Path (Get-ServiceDir $name) 'secrets' }

function Test-ServiceRegistered($name) {
    $svc = Read-ServicesConf | Where-Object { $_.Name -eq $name }
    return ($null -ne $svc)
}

function Get-ServiceDefinition($name) {
    return Read-ServicesConf | Where-Object { $_.Name -eq $name } | Select-Object -First 1
}

