function Get-ServiceEnv {
    param([string]$Name)

    $envVars = @{}

    # Load from .env file
    $envFile = Get-ServiceEnvFile $Name
    if (Test-Path $envFile) {
        Get-Content $envFile -Encoding ascii | ForEach-Object {
            $line = $_.Trim()
            if ($line -eq '' -or $line.StartsWith('#')) { return }
            $k, $v = $line -split '=', 2
            if ($k) { $envVars[$k.Trim()] = $v.Trim().Trim('"').Trim("'") }
        }
    }

    # Load from service config
    $confFile = Get-ServiceConfigFile $Name
    if (Test-Path $confFile) {
        Get-Content $confFile -Encoding ascii | ForEach-Object {
            $line = $_.Trim()
            if ($line -eq '' -or $line.StartsWith('#') -or $line -notmatch '=') { return }
            $k, $v = $line -split '=', 2
            $k = $k.Trim()
            if ($k -and -not $k.StartsWith('WINVPS_SVC_')) { $envVars[$k] = $v.Trim().Trim('"') }
        }
    }

    return $envVars
}

function Set-ServiceEnv {
    param([string]$Name, [hashtable]$Vars)

    $envFile = Get-ServiceEnvFile $Name
    $existing = @{}

    if (Test-Path $envFile) {
        Get-Content $envFile -Encoding ascii | ForEach-Object {
            $line = $_.Trim()
            if ($line -eq '' -or $line.StartsWith('#')) { return }
            $k, $v = $line -split '=', 2
            if ($k) { $existing[$k.Trim()] = $v.Trim() }
        }
    }

    foreach ($k in $Vars.Keys) { $existing[$k] = $Vars[$k] }

    $lines = @("# WinVPS Service Environment - $Name")
    foreach ($k in ($existing.Keys | Sort-Object)) {
        $lines += "$k=`"$($existing[$k])`""
    }
    $lines | Out-File -FilePath $envFile -Encoding ascii -Force
    Log "Environment updated for $Name"
}

function Remove-ServiceEnv {
    param([string]$Name, [string]$Key)

    $envFile = Get-ServiceEnvFile $Name
    if (-not (Test-Path $envFile)) { return }

    $lines = Get-Content $envFile -Encoding ascii | Where-Object {
        $_ -notmatch "^\s*\Q$Key\E\s*="
    }
    $lines | Out-File -FilePath $envFile -Encoding ascii -Force
}

