# ============================================================

function Show-ServiceDetail {
    param([string]$Name)

    $svc = Get-ServiceDefinition $Name
    if (-not $svc) { Err "Service '$Name' not found"; return }

    $status = Get-ServiceStatus $Name
    $metrics = Get-ServiceMetrics $Name
    $health = Test-ServiceHealth $Name
    $envVars = Get-ServiceEnv $Name

    Write-Host ''
    Write-Host "  ${Bold}$Name${NC} ${Dim}- $($svc.Description)${NC}"
    Write-Host "  ${Dim}------------------------------------------${NC}"
    Write-Host ''
    Write-Host "  ${Cyan}STATUS${NC}"
    Write-Host "    Status:    $(switch ($status) { 'running' { "${Green}* running${NC}" } default { "${Red}o stopped${NC}" } })"
    if ($metrics.Pid) { Write-Host "    PID:       $($metrics.Pid)" }
    if ($metrics.Uptime) { Write-Host "    Uptime:    $($metrics.Uptime)" }
    Write-Host ''
    Write-Host "  ${Cyan}CONFIGURATION${NC}"
    Write-Host "    Script:    $($svc.Script)"
    Write-Host "    Type:      $($svc.Type)"
    if ($svc.Port) { Write-Host "    Port:      $($svc.Port)" }
    Write-Host "    Auto-start:$($svc.AutoStart)"
    if ($svc.HealthCheck) { Write-Host "    Health:    $($svc.HealthCheck)" }
    if ($svc.DependsOn) { Write-Host "    Depends:   $($svc.DependsOn)" }
    Write-Host ''
    Write-Host "  ${Cyan}RESOURCES${NC}"
    Write-Host "    Memory:    $($metrics.MemoryMB) MB"
    Write-Host "    CPU:       $($metrics.CpuPercent)%"
    Write-Host "    Disk:      $($metrics.DiskMB) MB"
    Write-Host "    Logs:      $($metrics.LogMB) MB"
    Write-Host ''
    Write-Host "  ${Cyan}HEALTH${NC}"
    Write-Host "    Status:    $($health.Status)"
    Write-Host "    Message:   $($health.Message)"
    if ($health.Latency -gt 0) { Write-Host "    Latency:   $($health.Latency)ms" }
    Write-Host ''
    if ($envVars.Count -gt 0) {
        Write-Host "  ${Cyan}ENVIRONMENT${NC} ($($envVars.Count) vars)"
        foreach ($k in ($envVars.Keys | Sort-Object)) {
            $v = $envVars[$k]
            if ($k -match 'SECRET|KEY|TOKEN|PASSWORD') { $v = '***' }
            Write-Host "    $k=$v"
        }
        Write-Host ''
    }
}

# ============================================================
# --- SERVICE LIST ---
# ============================================================

function Show-ServiceList {
    $services = Read-ServicesConf
    Write-Host ''
    Write-Host "  ${Bold}Registered Services${NC} ($($services.Count))"
    Write-Host "  ${Dim}------------------------------------------${NC}"
    Write-Host ''

    # Table header
    Write-Host "  $($Dim)STATUS  NAME           TYPE     PORT   MEMORY   HEALTH${NC}"
    Write-Host "  $($Dim)------  ------------   ------   ----   ------   ------${NC}"

    foreach ($svc in $services) {
        $status = Get-ServiceStatus $svc.Name
        $icon = switch ($status) { 'running' { "${Green}*${NC}" } 'stopped' { "${Red}o${NC}" } default { "${Dim}?${NC}" }
        }
        $mem = if ($status -eq 'running') { "$($(Get-ServiceMemoryMB $svc.Name))MB" } else { '-' }
        $health = Test-ServiceHealth $svc.Name
        $healthIcon = switch ($health.Status) { 'healthy' { "${Green}+${NC}" } 'unhealthy' { "${Red}x${NC}" } default { "${Dim}-${NC}" } }
        $port = if ($svc.Port) { ":$($svc.Port)" } else { '-' }

        Write-Host "  $icon  $($svc.Name.PadRight(13)) $($svc.Type.PadRight(7)) $($port.PadRight(6)) $($mem.PadRight(7)) $healthIcon"
    }
    Write-Host ''
}

# ============================================================
# --- SERVICE EXEC ---
# ============================================================

function Invoke-ServiceExec {
    param([string]$Name, [string]$Command)

    if (-not (Test-ServiceRunning $Name)) { Err "Service '$Name' not running"; return }

    $svc = Get-ServiceDefinition $Name
    if (-not $svc) { Err "Service '$Name' not found"; return }

    $envVars = Get-ServiceEnv $Name
    foreach ($k in $envVars.Keys) {
        [Environment]::SetEnvironmentVariable($k, $envVars[$k], 'Process')
    }

    $workingDir = if ($svc.Script) { Split-Path $svc.Script -Parent } else { $WinVPSDir }
    if (-not (Test-Path $workingDir)) { $workingDir = $WinVPSDir }

    Write-Host "  ${Dim}Executing in $($svc.Name) context ($workingDir):${NC}"
    Write-Host "  ${Cyan}$Command${NC}"
    Write-Host ''

    try {
        $result = Invoke-Expression $Command 2>&1
        Write-Host $result
    } catch {
        Err "Execution failed: $_"
    }
}

# ============================================================
# --- SERVICE LOGS ---
# ============================================================

function Show-ServiceLogs {
    param([string]$Name, [int]$Lines = 100)

    if (-not $Name) {
        Write-Host ''
        Write-Host "  ${Bold}Available Service Logs${NC}"
        Write-Host "  ${Dim}------------------------------------------${NC}"
        Get-ChildItem -Path $ServicesDir -Directory -ErrorAction SilentlyContinue | ForEach-Object {
            $logDir = Join-Path $_.FullName 'logs'
            if (Test-Path $logDir) {
                $logs = Get-ChildItem -Path $logDir -Filter '*.log' -ErrorAction SilentlyContinue
                $totalSize = ($logs | Measure-Object -Property Length -Sum).Sum
                Write-Host "  $($_.Name.PadRight(15)) ${Dim}($([math]::Round(($totalSize / 1KB), 1))KB)${NC}"
            }
        }
        Write-Host ''
        return
    }

    $stdoutLog = Get-ServiceLogFile $Name 'stdout'
    $stderrLog = Get-ServiceLogFile $Name 'stderr'

    Write-Host ''
    Write-Host "  ${Bold}$Name logs${NC}"
    Write-Host "  ${Dim}------------------------------------------${NC}"

    if (Test-Path $stdoutLog) {
        Write-Host "  ${Green}stdout:${NC}"
        Get-Content $stdoutLog -Tail $Lines
    }

    if (Test-Path $stderrLog) {
        $stderrContent = Get-Content $stderrLog -Tail $Lines
        if ($stderrContent) {
            Write-Host "  ${Red}stderr:${NC}"
            Write-Host $stderrContent
        }
    }
    Write-Host ''
}

# ============================================================
# --- SERVICE BACKUP/RESTORE ---
# ============================================================

function Backup-Service {
    param([string]$Name)

    if (-not (Test-ServiceRegistered $Name)) { Err "Service '$Name' not found"; return }

    $dir = Get-ServiceDir $Name
    $ts = Get-Date -Format 'yyyyMMdd_HHmmss'
    $file = Join-Path $BackupDir "${Name}_backup_$ts.zip"

    if (-not (Test-Path $BackupDir)) { New-Item -ItemType Directory -Path $BackupDir -Force | Out-Null }

    Compress-Archive -Path (Join-Path $dir 'data'), (Join-Path $dir '.env'), (Join-Path $dir 'service.conf') `
        -DestinationPath $file -Force -ErrorAction SilentlyContinue

    $size = [math]::Round((Get-Item $file).Length / 1MB, 2)
    Log "Backup created: $file ($size MB)"
}

function Restore-Service {
    param([string]$Name)

    $latest = Get-ChildItem -Path $BackupDir -Filter "${Name}_backup_*.zip" -ErrorAction SilentlyContinue |
        Sort-Object LastWriteTime -Descending | Select-Object -First 1

    if (-not $latest) { Warn "No backup found for '$Name'"; return }

    $dir = Get-ServiceDir $Name
    Ensure-ServiceDir $Name
    Expand-Archive -Path $latest.FullName -DestinationPath $dir -Force
    Log "Restored from $($latest.Name)"
}

# ============================================================
# --- LOG ROTATION ---
# ============================================================

function Invoke-LogRotation {
    param([string]$Name, [int]$RetentionDays = 30)

    $logDir = Join-Path (Get-ServiceDir $Name) 'logs'
    if (-not (Test-Path $logDir)) { return }

    $cutoff = (Get-Date).AddDays(-$RetentionDays)
    Get-ChildItem -Path $logDir -Filter '*.log' -ErrorAction SilentlyContinue |
        Where-Object { $_.LastWriteTime -lt $cutoff } |
        ForEach-Object {
            Remove-Item $_.FullName -Force
            Log "Rotated old log: $($_.Name)"
        }
}

# ============================================================
# --- INSTALL DEPENDENCIES ---
# ============================================================

function Install-ServiceDependencies {
    param([string]$Name)

    $svc = Get-ServiceDefinition $Name
    if (-not $svc) { Err "Service '$Name' not found"; return }

    $workingDir = if ($svc.Script) { Split-Path $svc.Script -Parent } else { $WinVPSDir }
    if (-not (Test-Path $workingDir)) { Err "Working directory not found: $workingDir"; return }

    Log "Installing dependencies for $Name in $workingDir"

    switch ($svc.Type) {
        'node' {
            if (Test-Path (Join-Path $workingDir 'package.json')) {
                $bunLock = Test-Path (Join-Path $workingDir 'bun.lockb')
                $yarnLock = Test-Path (Join-Path $workingDir 'yarn.lock')
                $pnpmLock = Test-Path (Join-Path $workingDir 'pnpm-lock.yaml')
                Push-Location $workingDir
                if ($bunLock -and (Get-Command bun -ErrorAction SilentlyContinue)) {
                    Log "Running bun install..."
                    & bun install 2>&1
                } elseif ($pnpmLock -and (Get-Command pnpm -ErrorAction SilentlyContinue)) {
                    Log "Running pnpm install..."
                    & pnpm install 2>&1
                } elseif ($yarnLock -and (Get-Command yarn -ErrorAction SilentlyContinue)) {
                    Log "Running yarn install..."
                    & yarn install 2>&1
                } else {
                    Log "Running npm install..."
                    & npm install 2>&1
                }
                Pop-Location
                Log "Node dependencies installed"
            }
        }
        'python' {
            if (Test-Path (Join-Path $workingDir 'requirements.txt')) {
                Log "Running pip install..."
                Push-Location $workingDir
                & pip install -r requirements.txt 2>&1
                Pop-Location
                Log "pip install complete"
            } elseif (Test-Path (Join-Path $workingDir 'pyproject.toml')) {
                Log "Running pip install -e ...."
                Push-Location $workingDir
                & pip install -e . 2>&1
                Pop-Location
                Log "pip install complete"
            } elseif (Test-Path (Join-Path $workingDir 'Pipfile')) {
                Log "Running pipenv install..."
                Push-Location $workingDir
                & pipenv install 2>&1
                Pop-Location
                Log "pipenv install complete"
            } elseif (Test-Path (Join-Path $workingDir 'poetry.lock')) {
                Log "Running poetry install..."
                Push-Location $workingDir
                & poetry install 2>&1
                Pop-Location
                Log "poetry install complete"
            }
        }
        'go' {
            Log "Running go mod download..."
            Push-Location $workingDir
            & go mod download 2>&1
            Pop-Location
            Log "go mod download complete"
        }
        'dotnet' {
            Log "Running dotnet restore..."
            Push-Location $workingDir
            & dotnet restore 2>&1
            Pop-Location
            Log "dotnet restore complete"
        }
        'rust' {
            Log "Running cargo build..."
            Push-Location $workingDir
            & cargo build --release 2>&1
            Pop-Location
            Log "cargo build complete"
        }
        'ruby' {
            if (Test-Path (Join-Path $workingDir 'Gemfile')) {
                Log "Running bundle install..."
                Push-Location $workingDir
                & bundle install 2>&1
                Pop-Location
                Log "bundle install complete"
            }
        }
        'php' {
            if (Test-Path (Join-Path $workingDir 'composer.json')) {
                Log "Running composer install..."
                Push-Location $workingDir
                & composer install 2>&1
                Pop-Location
                Log "composer install complete"
            }
        }
        'java' {
            if (Test-Path (Join-Path $workingDir 'pom.xml')) {
                Log "Running mvn install..."
                Push-Location $workingDir
                & mvn install -DskipTests 2>&1
                Pop-Location
                Log "mvn install complete"
            } elseif (Test-Path (Join-Path $workingDir 'build.gradle') -or (Test-Path (Join-Path $workingDir 'build.gradle.kts'))) {
                Log "Running gradle build..."
                Push-Location $workingDir
                & gradle build 2>&1
                Pop-Location
                Log "gradle build complete"
            }
        }
        'deno' {
            Log "Deno caches dependencies on first run - no install step needed"
        }
        'bun' {
            if (Test-Path (Join-Path $workingDir 'package.json')) {
                Log "Running bun install..."
                Push-Location $workingDir
                & bun install 2>&1
                Pop-Location
                Log "bun install complete"
            }
        }
        default {
            Warn "No automatic dependency installer for type: $($svc.Type)"
        }
    }
}

